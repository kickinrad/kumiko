// A kit's generated text files start with a header saying so; the check fails one that lacks it.
// Contract (the systems guard reads the same): one of the first 10 lines matches HEADER_LINE.
import { extname } from "node:path";

const WINDOW = 10;
const block = (text) => `/* ${text} */`;
const line = (prefix) => (text) => `${prefix} ${text}`;
const html = (text) => `<!-- ${text} -->`;
const styles = {
  ".css": block, ".scss": block,
  ".js": line("//"), ".mjs": line("//"), ".ts": line("//"), ".kt": line("//"), ".kts": line("//"), ".swift": line("//"),
  ".yaml": line("#"), ".yml": line("#"), ".toml": line("#"), ".sh": line("#"), ".py": line("#"), ".conf": line("#"),
  ".md": html, ".html": html, ".svg": html, ".xml": html,
};
// What must stay first: front matter, doctype, xml declaration, shebang, @charset.
const leading = [
  /^---\r?\n(?:[\s\S]*?\r?\n)?---[ \t]*(?:\r?\n|$)/,
  /^<\?xml[^>]*\?>[ \t]*(?:\r?\n|$)/i,
  /^<!doctype[^>]*>[ \t]*(?:\r?\n|$)/i,
  /^#!.*(?:\r?\n|$)/,
  /^@charset[^;]*;[ \t]*(?:\r?\n|$)/,
];

// One line, opening with only comment marks, then "Generated by <name>", then "do not edit" on the same line.
export const HEADER_LINE = /^\W*Generated by \S+.*\bdo not edit\b/i;
export const hasHeader = (content) => content.split("\n", WINDOW).some((line) => HEADER_LINE.test(line));
export const wantsHeader = (path) => extname(path) in styles;

const text = ({ name, version }, target) => {
  const parts = [name, version, target];
  if (parts.some((part) => /[\r\n]|\*\/|-->/.test(part))) throw new Error(`Header text for ${target} cannot hold a newline, "*/" or "-->"`);
  return `Generated by kumiko from ${name} ${version}, output ${target}: do not edit; change the kit's inputs and rebuild.`;
};

// Returns the target's outputs with the header added to each text file that lacks one.
export const stamp = (outputs, kit, target) => outputs.map((output) => {
  if (!wantsHeader(output.path) || hasHeader(output.content)) return output;
  let head = "";
  let rest = output.content;
  for (const pattern of leading) {
    const match = rest.match(pattern);
    if (match) {
      head += match[0].endsWith("\n") ? match[0] : `${match[0]}\n`;
      rest = rest.slice(match[0].length);
    }
  }
  const content = `${head}${styles[extname(output.path)](text(kit, target))}\n${rest}`;
  if (!hasHeader(content)) throw new Error(`${output.path}: the header would land past line ${WINDOW}; shorten what comes first`);
  return { ...output, content };
});

// Under --check: the file on disk must carry the header, whatever else differs.
export const checkHeader = (path, existing) => {
  if (wantsHeader(path) && existing !== undefined && !hasHeader(existing)) {
    throw new Error(`${path} has no generated header in its first ${WINDOW} lines; run tokens`);
  }
};
