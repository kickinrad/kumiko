// The claude-design output: the kit as a Claude Design System artifact's files (tests/playground/ is the kit).
import { expect, test } from "bun:test";
import { cpSync, mkdtempSync, renameSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { version as beerVersion } from "beercss/package.json";
import specimens from "../src/web/components.js";
import { HEADER_LINE } from "../src/header.mjs";
import { read, root, run } from "./helpers";

// The fixture kit with this output after its css and beer outputs, and `edit` applied to the config.
const project = (edit = "") => {
  const dir = mkdtempSync(join(tmpdir(), "tokens-claude-design-"));
  for (const entry of ["design", "tokens", "VERSION", "kumiko.config.mjs"]) cpSync(join(root, "tests/playground", entry), join(dir, entry), { recursive: true });
  renameSync(join(dir, "kumiko.config.mjs"), join(dir, "base.config.mjs"));
  writeFileSync(join(dir, "kumiko.config.mjs"), `import base from "./base.config.mjs";\nconst c = structuredClone(base);\nc.targets.push("claude-design");\nc["claude-design"] = { path: "ports/claude-design" };\n${edit}\nexport default c;\n`);
  return dir;
};
const built = (dir = project()) => {
  const result = run(dir);
  expect(result.stderr.toString()).toBe("");
  expect(result.exitCode).toBe(0);
  return dir;
};
const file = (dir: string, path: string) => read(dir, `ports/claude-design/project/${path}`);

test("writes the system's files with the markers its page reads on line 1, and --check passes on them", () => {
  const dir = built();
  expect(file(dir, "tokens.css").split("\n").slice(0, 2)).toEqual(["/* acme — generated from tokens.json */", expect.stringMatching(HEADER_LINE)]);
  expect(file(dir, "components/Button/preview.html").split("\n").slice(0, 2)).toEqual(['<!-- @dsCard group="Actions" height=240 -->', expect.stringMatching(HEADER_LINE)]);
  expect(file(dir, "components/Cover/preview.html")).toStartWith("<!-- @dsCard height=288 -->\n");
  expect(file(dir, "components/bundle.js")).toContain("window.Acme = {};");
  expect(run(dir, "--check").exitCode).toBe(0);
});

test("the README is the notes without their title, under a header markdown hides, then the kit's exceptions", () => {
  const readme = file(built(), "README.md");
  expect(readme.split("\n")[0]).toMatch(/^\[\/\/\]: # \(Generated by kumiko .*do not edit.*\)$/);
  expect(readme).not.toMatch(/^# /m);
  expect(readme).toContain("## Exceptions to Material 3");
});

test("tokens.json: a theme per mode, pinned as the css output pins them, in the list shape the page reads", () => {
  const data = JSON.parse(file(built(), "tokens.json"));
  expect(data.name).toBe("acme");
  expect(data.color.themes).toEqual([{ id: "dark", name: "Night" }, { id: "light", name: "Day" }]);
  const primary = data.color.tokens.find((token: { name: string }) => token.name === "md-sys-color-primary");
  expect(primary.value).toEqual({ dark: "#7aa2f7", light: "#2e7de9" });
  expect(primary.usage).toBe("Material 3's primary role.");
  for (const token of data.color.tokens) {
    expect(token.name).toMatch(/^[A-Za-z0-9][A-Za-z0-9_.-]{0,63}$/);
    expect(token.name).not.toStartWith("md-comp-");
  }
  expect(data.type.groups.map((group: { name: string }) => group.name)).toEqual(["Display", "Headline", "Title", "Body", "Label"]);
  expect(Object.keys(data.type.families)).toContain("plain");
  expect(data.radius.tokens.map((token: { name: string }) => token.name)).toContain("md-sys-shape-corner-full");
});

test("each specimen is a preview in its Material family with a README, loading Beer's script at the installed version", () => {
  const dir = built();
  for (const item of specimens) {
    const name = item.id.split("-").map((part: string) => part[0].toUpperCase() + part.slice(1)).join("");
    expect(file(dir, `components/${name}/preview.html`)).toStartWith(`<!-- @dsCard group="${item.family}" `);
    expect(file(dir, `components/${name}/preview.html`)).toContain(`beercss@${beerVersion}/dist/cdn/beer.min.js`);
    expect(file(dir, `components/${name}/README.md`)).toContain(`# ${item.name}`);
  }
  const bundle = file(dir, "components/bundle.css");
  expect(bundle.indexOf("@layer beer {")).toBeLessThan(bundle.indexOf("--md-sys-color-primary"));
  expect(bundle).toContain("Material+Symbols+Outlined");
});

test("the cover carries the theme's tagline when it has one", () => {
  expect(file(built(), "components/Cover/preview.html")).not.toContain("font-size:14px");
  const dir = project();
  writeFileSync(join(dir, "design/theme.toml"), `tagline = "Ink on paper."\n${read(dir, "design/theme.toml")}`);
  expect(file(built(dir), "components/Cover/preview.html")).toContain("Ink on paper.");
});

test.each(["css", "beer"])("a config without the %s output before it fails, naming it", (target) => {
  const result = run(project(`c.targets = c.targets.filter((each) => each !== "${target}" && each !== "playground");`));
  expect(result.exitCode).toBe(1);
  expect(result.stderr.toString()).toContain(`claude-design needs the ${target} output, listed before it`);
});
