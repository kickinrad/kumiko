// `tokens lint` fails a consumer's hand-typed colour, motion, type size or radius.
import { expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const command = process.env.TOKENS_BIN ? [resolve(process.env.TOKENS_BIN)] : ["bun", join(root, "bin/tokens.mjs")];
const lint = (dir: string, ...paths: string[]) => {
  const result = Bun.spawnSync([...command, "lint", ...paths], { cwd: dir, stderr: "pipe", stdout: "pipe" });
  return { code: result.exitCode, out: result.stdout.toString(), err: result.stderr.toString() };
};
const project = (files: Record<string, string>) => {
  const dir = mkdtempSync(join(tmpdir(), "lint-"));
  for (const [path, content] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, path)), { recursive: true });
    writeFileSync(join(dir, path), content);
  }
  return dir;
};
const flagged = (name: string, content: string, line: string) => {
  const result = lint(project({ [name]: content }), name);
  expect(result.code).toBe(1);
  expect(result.out.trim()).toBe(`${name}:${line}`);
};

test("colour: hex, rgb() and Kotlin Color(0x) fail; 3-digit hex and var() pass", () => {
  flagged("a.css", "a { color: #1a2b3c; }\n", "1: colour: #1a2b3c");
  flagged("a.css", "a { color: #1a2b3cff; }\n", "1: colour: #1a2b3cff");
  flagged("a.css", "a { color: rgba(0, 0, 0, .5); }\n", "1: colour: rgba(0");
  flagged("A.kt", "val c = Color(0xFF112233)\n", "1: colour: Color(0xFF112233");
  expect(lint(project({ "a.css": "a { color: var(--md-primary); } /* see #107 */\n" }), "a.css").code).toBe(0);
});

test("motion: literal durations in transition/animation, cubic-bezier and tween(n) fail", () => {
  flagged("a.css", "a { transition: opacity 120ms ease; }\n", "1: motion: 120ms");
  flagged("a.css", "a { animation: spin 6s linear; }\n", "1: motion: 6s");
  flagged("a.css", "a { transition: opacity var(--d) cubic-bezier(.2, 0, 0, 1); }\n", "1: motion: cubic-bezier(");
  flagged("Home.kt", "val s = tween(160)\n", "1: motion: 160");
  const clean = "a { transition: opacity var(--md-motion-short); }\nval s = tween(Motion.Short)\n.slow { width: 10s; }\n";
  expect(lint(project({ "a.css": clean }), "a.css").code).toBe(0);
});

test("type size: font-size px and Kotlin .sp fail", () => {
  flagged("a.css", "a { font-size: 14px; }\n", "1: type size: 14px");
  flagged("T.kt", "val t = TextStyle(fontSize = 24.sp)\n", "1: type size: 24.sp");
  expect(lint(project({ "a.css": "a { font-size: var(--md-body); }\n" }), "a.css").code).toBe(0);
});

test("radius: border-radius px and RoundedCornerShape dp fail", () => {
  flagged("a.css", "a { border-radius: 12px; }\n", "1: radius: 12px");
  flagged("S.kt", "val s = RoundedCornerShape(8.dp)\n", "1: radius: 8.dp");
  expect(lint(project({ "a.css": "a { border-radius: var(--md-shape-md); }\n" }), "a.css").code).toBe(0);
});

test("the same CSS inside a YAML or Python string is found", () => {
  flagged("card.yaml", "style: |\n  ha-card { border-radius: 16px; }\n", "2: radius: 16px");
  flagged("gen.py", 'row = "font-size: 13px"\n', "1: type size: 13px");
});

test("zero values pass", () => {
  const zero = "a { border-radius: 0; font-size: 0px; margin: 0 }\nb { border-radius: 0px 0px; }\nval s = RoundedCornerShape(0.dp)\nval t = 0.sp\n";
  expect(lint(project({ "a.css": zero, "Z.kt": zero }), "a.css", "Z.kt").code).toBe(0);
});

test("a file with the generated header is skipped", () => {
  const generated = "/* Generated by kumiko (tokens 1.0.0) from kit 1: do not edit; rebuild. */\na { color: #112233; }\n";
  expect(lint(project({ "a.css": generated }), "a.css").code).toBe(0);
});

test("`lint: own <why>` skips its line; an empty reason does not", () => {
  const dir = project({ "a.css": "a { color: #112233; } /* lint: own brand mark */\n", "b.css": "a { color: #112233; } /* lint: own */\n" });
  expect(lint(dir, "a.css").code).toBe(0);
  expect(lint(dir, "b.css").out.trim()).toBe("b.css:1: colour: #112233");
});

test("a directory is walked; node_modules, dot-directories and other extensions are skipped", () => {
  const bad = "a { color: #112233; }\n";
  const dir = project({
    "src/deep/a.css": bad, "src/node_modules/x.css": bad, "src/.cache/y.css": bad, "src/notes.txt": bad, "src/b.css": "a{}\n",
  });
  const result = lint(dir, "src");
  expect(result.code).toBe(1);
  expect(result.out.trim()).toBe(`${join("src", "deep", "a.css")}:1: colour: #112233`);
});

test("exit 0 and no output when clean; a missing path fails naming it", () => {
  const dir = project({ "a.css": "a { color: var(--c); }\n" });
  expect(lint(dir, ".")).toEqual({ code: 0, out: "", err: "" });
  const missing = lint(dir, "a.css", "nope");
  expect(missing.code).toBe(1);
  expect(missing.err).toContain("nope");
});
