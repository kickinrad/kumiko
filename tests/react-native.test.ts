import { expect, test } from "bun:test";
import { cpSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { read, root, run } from "./helpers";

const project = () => {
  const dir = mkdtempSync(join(tmpdir(), "kumiko-react-native-"));
  for (const entry of ["design", "VERSION"]) cpSync(join(root, "tests/outputs", entry), join(dir, entry), { recursive: true });
  writeFileSync(join(dir, "kumiko.config.mjs"), `export default { targets: ["react-native"], include: ["builtin:material"], kit: { name: "acme" }, "react-native": { path: "ports/react-native/tokens.ts" } };\n`);
  return dir;
};

test("react-native writes typed mode tokens and native text styles", async () => {
  const dir = project();
  const result = run(dir);
  expect(result.exitCode).toBe(0);
  const source = read(dir, "ports/react-native/tokens.ts");
  expect(source.split("\n")[0]).toMatch(/Generated by kumiko.*do not edit/);
  expect(source).toContain("export const tokens = {");
  expect(source).toContain("export type ThemeMode = keyof typeof tokens;");
  expect(source).toContain("export type ThemeTokens = (typeof tokens)[ThemeMode];");
  expect(source).toContain('"primary": "#7aa2f7"');
  expect(source).toContain('"primary": "#2e7de9"');
  expect(source).toContain('"card-gap": 8');
  expect(source).toContain('"medium": 12');
  expect(source).toContain('"fontFamily": "Some Mono"');
  expect(source).toContain('"fontWeight": "500"');
  expect(run(dir, "--check").exitCode).toBe(0);
  const module = await import(join(dir, "ports/react-native/tokens.ts"));
  expect(module.tokens.night.md.comp).toBeUndefined();
  expect(module.tokens.night.md.sys.color.primary).toBe("#7aa2f7");
  expect(module.tokens.day.md.sys.color.primary).toBe("#2e7de9");
  expect(module.tokens.night.acme.layout["card-gap"]).toBe(8);
  expect(module.textStyles.night["label-large"].fontFamily).toBe("Some Mono");
  expect(module.textStyles.night["label-large"].fontSize).toBeGreaterThan(0);
});

test("react-native requires a kit, output path and exactly one light/dark counterpart", () => {
  const dir = project();
  writeFileSync(join(dir, "kumiko.config.mjs"), 'export default { targets: ["react-native"], include: ["builtin:material"], kit: { name: "acme" } };\n');
  expect(run(dir).stderr.toString()).toContain('option "path" is required');
  writeFileSync(join(dir, "kumiko.config.mjs"), 'export default { targets: ["react-native"], include: ["builtin:material"], "react-native": { path: "out.ts" } };\n');
  expect(run(dir).stderr.toString()).toContain("needs a declared kit");
});

test("react-native refuses relative CSS dimensions", () => {
  const dir = project();
  const theme = read(dir, "design/theme.toml").replace('"acme.layout.card-gap" = "8px"', '"acme.layout.card-gap" = "1rem"');
  writeFileSync(join(dir, "design/theme.toml"), theme);
  expect(run(dir).stderr.toString()).toContain("acme.layout.card-gap must use px");
});
