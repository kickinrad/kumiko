// The playground output: one kit-agnostic page on the kit's web outputs, a client, and tokens.json (tests/playground/ is the kit).
import { expect, test } from "bun:test";
import { cpSync, mkdtempSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { contrast } from "../src/color.mjs";
import { HEADER_LINE } from "../src/header.mjs";

const root = resolve(import.meta.dir, "..");
const command = process.env.TOKENS_BIN ? [resolve(process.env.TOKENS_BIN)] : ["bun", join(root, "bin/tokens.mjs")];
const run = (cwd: string, ...args: string[]) => Bun.spawnSync([...command, ...args], { cwd, stderr: "pipe" });
const read = (dir: string, file: string) => readFileSync(join(dir, file), "utf8");

const project = () => {
  const dir = mkdtempSync(join(tmpdir(), "tokens-playground-"));
  for (const entry of ["design", "tokens", "VERSION", "tokens.config.mjs"]) cpSync(join(root, "tests/playground", entry), join(dir, entry), { recursive: true });
  return dir;
};
// The fixture's config with `edit` applied to a copy of its options.
const edited = (edit: string) => {
  const dir = project();
  renameSync(join(dir, "tokens.config.mjs"), join(dir, "base.config.mjs"));
  writeFileSync(join(dir, "tokens.config.mjs"), `import base from "./base.config.mjs";\nconst c = structuredClone(base);\n${edit}\nexport default c;\n`);
  return dir;
};
// A kit's generated text starts with a header that names the kit (the engine's rule); the page itself names none.
const body = (text: string) => text.split("\n").filter((line) => !HEADER_LINE.test(line)).join("\n");
const built = (dir = project()) => {
  const result = run(dir);
  expect(result.stderr.toString()).toBe("");
  expect(result.exitCode).toBe(0);
  return dir;
};
const client = async (dir: string) => ({ ...(await import(join(dir, "docs/play/playground.js"))), ...(await import(join(dir, "docs/play/foundations.js"))) });

test("writes index.html, playground.js and tokens.json, and --check passes on them", () => {
  const dir = built();
  for (const file of ["index.html", "playground.js", "tokens.json"]) expect(read(dir, `docs/play/${file}`).length).toBeGreaterThan(0);
  expect(read(dir, "docs/play/index.html")).toStartWith("<!doctype html>\n<!-- Generated by kumiko");
  expect(read(dir, "docs/play/playground.js")).toStartWith("// Generated by kumiko");
  expect(run(dir, "--check").exitCode).toBe(0);
  writeFileSync(join(dir, "docs/play/playground.js"), `${read(dir, "docs/play/playground.js")}// edit\n`);
  expect(run(dir, "--check").stderr.toString()).toContain("docs/play/playground.js is stale");
});

test("the page and the client name no kit, and the client imports only its files beside the page", () => {
  const dir = built();
  for (const file of ["index.html", "playground.js", "foundations.js", "components.js", "cards.js", "pages.js", "color.mjs"]) {
    const text = body(read(dir, `docs/play/${file}`));
    expect(text, file).not.toMatch(/acme/i);
    for (const [, from] of text.matchAll(/^import .* from "([^"]+)";$/gm)) expect(from, file).toMatch(/^\.\/[a-z]+\.m?js$/);
  }
  const page = read(dir, "docs/play/index.html");
  expect(page).toContain('@import url("https://cdn.jsdelivr.net/npm/beercss/dist/cdn/beer.min.css") layer(beer);');
  expect(page).toContain('src="https://cdn.jsdelivr.net/npm/beercss/dist/cdn/beer.min.js"');
  expect(page).toContain('src="playground.js"');
});

test("tokens.json holds the kit's name, version, both modes' tokens and the notes", () => {
  const data = JSON.parse(read(built(), "docs/play/tokens.json"));
  expect(Object.keys(data)).toEqual(["name", "version", "modes", "notes"]);
  expect(data.name).toBe("acme");
  expect(data.version).toBe("1.2.3");
  expect(Object.keys(data.modes)).toEqual(["night", "day"]);
  const at = (mode: string, path: string) => data.modes[mode].find((token: { path: string }) => token.path === path);
  expect(at("night", "md.sys.color.primary")).toEqual({ path: "md.sys.color.primary", value: "#7aa2f7", type: "color" });
  expect(at("day", "md.sys.color.primary").value).toBe("#2e7de9");
  expect(at("night", "acme.gap")).toEqual({ path: "acme.gap", value: "8px", type: "dimension", description: "The gap between two cards." });
  expect(at("day", "acme.gap").value).toBe("8px");
  expect(data.notes).toBe(read(join(root, "tests/playground"), "design/notes.md"));
});

test("a kit with no notes.md has no notes, and a kit with no theme names its modes base and by query", () => {
  const dir = project();
  rmSync(join(dir, "design/notes.md"));
  built(dir);
  expect("notes" in JSON.parse(read(dir, "docs/play/tokens.json"))).toBe(false);

  const plain = edited('c.media = { "(prefers-color-scheme: light)": ["tokens/day.tokens.json"] }; c.kit.root = "none";');
  writeFileSync(join(plain, "tokens/day.tokens.json"), '{"md":{"sys":{"color":{"primary":{"$type":"color","$value":"#112233"}}}}}');
  built(plain);
  expect(Object.keys(JSON.parse(read(plain, "docs/play/tokens.json")).modes)).toEqual(["base", "(prefers-color-scheme: light)"]);
});

test.each([
  ["docs/play", "ports/css/kit.css", "ports/css/kit-beer.css", "../../ports/css/kit.css", "../../ports/css/kit-beer.css"],
  ["ports/css", "ports/css/kit.css", "ports/css/kit-beer.css", "kit.css", "kit-beer.css"],
  ["ports", "ports/css/kit.css", "ports/css/kit-beer.css", "css/kit.css", "css/kit-beer.css"],
  [".", "ports/css/kit.css", "ports/css/kit-beer.css", "ports/css/kit.css", "ports/css/kit-beer.css"],
])("the page at %s reaches the kit's css and beer outputs by relative paths", (path, css, beer, cssHref, beerHref) => {
  const dir = built(edited(`c.playground = { path: "${path}", css: "${css}", beer: "${beer}" };`));
  const page = read(dir, `${path}/index.html`);
  expect(page).toContain(`<link rel="stylesheet" href="${cssHref}">`);
  expect(page).toContain(`<link rel="stylesheet" href="${beerHref}">`);
  expect(page.indexOf(cssHref)).toBeLessThan(page.indexOf(beerHref));
});

test.each(["path", "css", "beer"])("a missing %s fails, naming it", (option) => {
  const result = run(edited(`delete c.playground.${option};`));
  expect(result.exitCode).toBe(1);
  expect(result.stderr.toString()).toContain(`playground option "${option}" is required`);
});

test("without a declared kit it fails, saying so", () => {
  const dir = project();
  writeFileSync(join(dir, "tokens.config.mjs"), 'export default { targets: ["playground"], playground: { path: "p", css: "a.css", beer: "b.css" } };\n');
  const result = run(dir);
  expect(result.exitCode).toBe(1);
  expect(result.stderr.toString()).toContain("needs a declared kit");
});

test("markdown: headings (under the item's own h1), paragraphs, lists and inline code, and nothing else", async () => {
  const { markdown } = await client(built());
  expect(markdown("# Title\n\nOne line\nwraps `code` here.\n\n## Sub\n\n- a\n  more\n- b\n\n1. x\n2. y\n")).toBe([
    "<h2>Title</h2>",
    "<p>One line wraps <code>code</code> here.</p>",
    "<h3>Sub</h3>",
    "<ul><li>a more</li><li>b</li></ul>",
    "<ol><li>x</li><li>y</li></ol>",
  ].join("\n"));
  expect(markdown("<b>x</b> **y** [z](q)")).toBe("<p>&lt;b&gt;x&lt;/b&gt; **y** [z](q)</p>");
  expect(markdown("###### six")).toBe("<h6>six</h6>");
});

test("colour: a tile per role that is not an on-colour, in the role's colour under its on-colour, with the ratio the engine computes", async () => {
  const dir = built();
  const { colour } = await client(dir);
  const data = JSON.parse(read(dir, "docs/play/tokens.json"));
  for (const mode of ["night", "day"]) {
    const html: string = colour(data.modes[mode]);
    const value = (path: string) => data.modes[mode].find((token: { path: string }) => token.path === path).value;
    const ratio = (role: string, on: string) => `${contrast(value(`md.sys.color.${on}`), value(`md.sys.color.${role}`)).toFixed(2)}:1`;
    expect(html).toContain(`background: var(--md-sys-color-primary); color: var(--md-sys-color-on-primary)`);
    expect(html).toContain(`on-primary ${ratio("primary", "on-primary")}`);
    expect(html).toContain(`on-surface ${ratio("surface-container", "on-surface")}`);
    expect(html).toContain(`inverse-on-surface ${ratio("inverse-surface", "inverse-on-surface")}`);
    expect(html).not.toContain("<b>on-primary</b>");
  }
});

test("view: five destinations in a rail and a bar, the open item in a list-detail, one pane at a time on small", async () => {
  const dir = built();
  const { view } = await client(dir);
  const data = JSON.parse(read(dir, "docs/play/tokens.json"));
  const state = { tab: "rules", item: "notes", mode: "night" };
  const open: string = view(data, state);
  for (const name of ["Foundations", "Components", "Cards", "Pages", "Rules"]) expect(open.match(new RegExp(`<div>${name}</div>`, "g"))).toHaveLength(2);
  expect(open).toContain('<nav class="left m l"');
  expect(open).toContain('<nav class="bottom s"');
  expect(open).toContain("<h3>Don't</h3>");
  expect(open).toContain('href="#rules"');
  expect(open).toContain("acme");
  expect(open.match(/<h1>/g)).toHaveLength(1);
  // An item is named: the list hides on small, and a back button shows there.
  expect(open).toContain('<div class="s12 m4 l3 m l">');
  expect(open).toContain('class="button circle transparent s"');
  expect(open).toContain('<div class="s12 m8 l9">');
  // Only a tab is named: the detail hides on small, and there is nothing to go back to.
  const list: string = view(data, { ...state, item: undefined });
  expect(list).toContain('<div class="s12 m4 l3">');
  expect(list).toContain('<div class="s12 m8 l9 m l">');
  expect(list).not.toContain('class="button circle transparent s"');
  // Nothing named: the first destination's first item.
  expect(view(data, { mode: "night" })).toContain("<h1>Colour</h1>");
  // The mode switch names the modes and marks the current one.
  expect(open).toContain('<button class="active" data-mode="night">Night</button>');
  expect(open).toContain('<button data-mode="day">Day</button>');
});

